// One-time generator: converts src/data/products.js into a SQL seed for the
// new category-driven products schema (products + product_images +
// pharmacy_product_details/benefits + chemical_product_details/quantity
// options/packaging options/documents).
//
// Run once with: node backend/database/migrations/generate_product_catalog_v2_seed.mjs
// Output: backend/database/migrations/seed_product_catalog_v2.sql

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const productsPath = path.resolve(__dirname, '../../../src/data/products.js');
const outPath = path.resolve(__dirname, 'seed_product_catalog_v2.sql');

const { products } = await import(pathToFileURL(productsPath).href);

// src/data/products.js has some pre-existing mojibake (UTF-8 bytes that were
// misread as Windows-1252 and re-saved as UTF-8, e.g. "Bakerâ„¢" instead of
// "Baker™"). Repair it here rather than propagating garbled text onto real
// product pages — this is a read-only decode fix, the source file is untouched.
const WIN1252_HIGH = {
  0x20AC: 0x80, 0x201A: 0x82, 0x0192: 0x83, 0x201E: 0x84, 0x2026: 0x85, 0x2020: 0x86, 0x2021: 0x87,
  0x02C6: 0x88, 0x2030: 0x89, 0x0160: 0x8A, 0x2039: 0x8B, 0x0152: 0x8C, 0x017D: 0x8E, 0x2018: 0x91,
  0x2019: 0x92, 0x201C: 0x93, 0x201D: 0x94, 0x2022: 0x95, 0x2013: 0x96, 0x2014: 0x97, 0x02DC: 0x98,
  0x2122: 0x99, 0x0161: 0x9A, 0x203A: 0x9B, 0x0153: 0x9C, 0x017E: 0x9E, 0x0178: 0x9F,
};

function fixMojibake(value) {
  if (typeof value !== 'string') return value;
  const bytes = [];
  for (const ch of value) {
    const cp = ch.codePointAt(0);
    if (cp <= 0xff) bytes.push(cp);
    else if (WIN1252_HIGH[cp] !== undefined) bytes.push(WIN1252_HIGH[cp]);
    else return value; // not recognizable mojibake — leave untouched
  }
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(Uint8Array.from(bytes));
  } catch {
    return value;
  }
}

function deepFixMojibake(value) {
  if (typeof value === 'string') return fixMojibake(value);
  if (Array.isArray(value)) return value.map(deepFixMojibake);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, deepFixMojibake(v)]));
  }
  return value;
}

// arion_pharmacy top-level category slug -> id (matches the live categories table)
const CATEGORY_ID_BY_SLUG = {
  medicines: 1,
  vitamins: 2,
  'personal-care': 3,
  'baby-care': 4,
  'lifestyle-fitness': 5,
  'sexual-wellness': 6,
  organic: 7,
  'healthcare-device': 8,
  obesity: 9,
  'performance-and-wellness': 10,
  'laboratory-chemicals': 11,
};

function sqlString(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  return "'" + String(value).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
}

function sqlNumber(value) {
  if (value === null || value === undefined || Number.isNaN(value)) return 'NULL';
  return String(value);
}

function sqlDate(value) {
  // "Dec 18, 2025" / "2025-12-18" -> 'YYYY-MM-DD'; "Dec 2025" -> 'YYYY-MM-01'; else NULL
  if (!value) return 'NULL';
  const parsed = new Date(value.includes(',') || /\d{4}-\d{2}-\d{2}/.test(value) ? value : `1 ${value}`);
  if (Number.isNaN(parsed.getTime())) return 'NULL';
  const iso = parsed.toISOString().slice(0, 10);
  return sqlString(iso);
}

const lines = [];
lines.push('-- Generated by generate_product_catalog_v2_seed.mjs — do not hand-edit.');
lines.push(`-- Imports all ${products.length} products from src/data/products.js into the`);
lines.push('-- category-driven products/pharmacy_*/chemical_* schema. Slugs are preserved');
lines.push('-- verbatim so /product/{slug} keeps resolving the same product.');
lines.push('');

for (const raw of products) {
  const p = deepFixMojibake(raw);
  const categoryId = CATEGORY_ID_BY_SLUG[p.category];
  if (!categoryId) {
    console.warn(`Skipping "${p.name}" — unknown category "${p.category}"`);
    continue;
  }

  const isChemical = p.category === 'laboratory-chemicals';
  const productType = isChemical ? 'chemical' : 'pharmacy';
  const badge = Array.isArray(p.badges) && p.badges.length > 0 ? p.badges[0] : null;
  const stockStatus = (p.stock ?? 0) > 0 ? 'in_stock' : 'out_of_stock';

  const basePrice = isChemical
    ? (Array.isArray(p.quantities) && p.quantities[0]?.price != null ? p.quantities[0].price : p.price)
    : (p.salePrice ?? p.price);

  lines.push(`-- ${p.name}`);
  lines.push('INSERT INTO `products`');
  lines.push('  (`name`, `slug`, `category_id`, `product_type`, `manufacturer_or_brand`, `form`, `sku`, `base_price`, `badge_label`, `description_text`, `stock_status`, `is_active`)');
  lines.push('VALUES');
  lines.push(
    '  (' + [
      sqlString(p.name),
      sqlString(p.slug),
      sqlNumber(categoryId),
      sqlString(productType),
      sqlString(p.brand ?? 'Generic'),
      sqlString(p.form ?? null),
      sqlString(null), // no sku in static data
      sqlNumber(basePrice),
      sqlString(badge),
      sqlString(p.description ?? null),
      sqlString(stockStatus),
      1,
    ].join(', ') + ');'
  );
  lines.push('SET @pid = LAST_INSERT_ID();');

  // Images: main image + gallery, deduped, in order
  const images = [p.image, ...(Array.isArray(p.gallery) ? p.gallery : [])]
    .filter((img, idx, arr) => img && arr.indexOf(img) === idx);
  if (images.length > 0) {
    lines.push('INSERT INTO `product_images` (`product_id`, `image_url`, `sort_order`) VALUES');
    lines.push(images.map((img, idx) => `  (@pid, ${sqlString(img)}, ${idx + 1})`).join(',\n') + ';');
  }

  if (!isChemical) {
    const originalPrice = p.salePrice ? p.price : null;
    const discountPercent = p.salePrice ? Math.round(((p.price - p.salePrice) / p.price) * 100) : null;

    lines.push('INSERT INTO `pharmacy_product_details` (`product_id`, `net_weight`, `original_price`, `discount_percent`, `directions_for_use`) VALUES');
    lines.push(
      '  (@pid, ' + [
        sqlString(p.weight ?? null),
        sqlNumber(originalPrice),
        sqlNumber(discountPercent),
        sqlString(p.directions ?? null),
      ].join(', ') + ');'
    );

    if (Array.isArray(p.keyBenefits) && p.keyBenefits.length > 0) {
      lines.push('INSERT INTO `pharmacy_product_benefits` (`product_id`, `benefit_text`, `sort_order`) VALUES');
      lines.push(p.keyBenefits.map((b, idx) => `  (@pid, ${sqlString(b)}, ${idx + 1})`).join(',\n') + ';');
    }
  } else {
    const spec = p.labSpecifications ?? {};
    lines.push('INSERT INTO `chemical_product_details`');
    lines.push('  (`product_id`, `cas_number`, `chemical_name_of_material`, `boiling_point`, `melting_point`, `molecular_formula`, `molecular_weight`, `percent_purity`, `color`, `synonym`, `grade`, `unit_size`, `molecule_diagram_url`)');
    lines.push('VALUES');
    lines.push(
      '  (@pid, ' + [
        sqlString(spec['CAS'] ?? null),
        sqlString(spec['Chemical Name of Material'] ?? spec['Chemical Name'] ?? null),
        sqlString(spec['Boiling Point'] ?? null),
        sqlString(spec['Melting Point'] ?? null),
        sqlString(spec['Molecular Formula'] ?? null),
        sqlString(spec['Molecular Weight (g/mol)'] ?? spec['Molecular Weight'] ?? null),
        sqlString(spec['Percent Purity'] ?? spec['Purity'] ?? null),
        sqlString(spec['Color'] ?? null),
        sqlString(spec['Synonym'] ?? null),
        sqlString(spec['Grade'] ?? null),
        sqlString(spec['Unit Size'] ?? null),
        sqlString(p.image ?? null),
      ].join(', ') + ');'
    );

    if (Array.isArray(p.quantities) && p.quantities.length > 0) {
      lines.push('INSERT INTO `chemical_product_quantity_options` (`product_id`, `label`, `price_override`, `is_default`, `sort_order`) VALUES');
      lines.push(p.quantities.map((q, idx) =>
        `  (@pid, ${sqlString(q.label)}, ${sqlNumber(q.price)}, ${idx === 0 ? 1 : 0}, ${idx + 1})`
      ).join(',\n') + ';');
    }

    if (Array.isArray(p.packaging) && p.packaging.length > 0) {
      lines.push('INSERT INTO `chemical_product_packaging_options` (`product_id`, `label`, `is_default`, `sort_order`) VALUES');
      lines.push(p.packaging.map((pkg, idx) =>
        `  (@pid, ${sqlString(pkg.label)}, ${pkg.default ? 1 : 0}, ${idx + 1})`
      ).join(',\n') + ';');
    }

    const docs = p.documents ?? {};
    const docRows = [];
    (docs.certificates ?? []).forEach((c, idx) => docRows.push([
      'certificate', c.type ?? 'Certificate of Analysis', c.lotNumber ?? null, c.type ?? null,
      sqlDate(c.date), c.catalogNumbers ?? null, c.url ?? '', idx + 1,
    ]));
    (docs.sds ?? []).forEach((d, idx) => docRows.push([
      'safety_data_sheet', d.title, null, null, sqlDate(d.lastUpdated), null, d.url ?? '', idx + 1,
    ]));
    (docs.datasheets ?? []).forEach((d, idx) => docRows.push([
      'product_information', d.title, null, null, 'NULL', null, d.url ?? '', idx + 1,
    ]));
    (docs.brochures ?? []).forEach((d, idx) => docRows.push([
      'scientific_resource', d.title, null, null, 'NULL', null, d.url ?? '', idx + 1,
    ]));

    if (docRows.length > 0) {
      lines.push('INSERT INTO `chemical_product_documents` (`product_id`, `doc_group`, `title`, `lot_number`, `certificate_type`, `document_date`, `catalog_numbers`, `file_url`, `sort_order`) VALUES');
      // file_url is NOT NULL — fall back to '#' rather than letting sqlString collapse '' to NULL.
      lines.push(docRows.map(([group, title, lot, certType, date, catNums, url, sort]) =>
        `  (@pid, ${sqlString(group)}, ${sqlString(title)}, ${sqlString(lot)}, ${sqlString(certType)}, ${date === 'NULL' ? 'NULL' : date}, ${sqlString(catNums)}, ${sqlString(url || '#')}, ${sort})`
      ).join(',\n') + ';');
    }
  }

  lines.push('');
}

writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote seed for ${products.length} products to ${outPath}`);
