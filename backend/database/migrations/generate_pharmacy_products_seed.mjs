// One-time generator: converts src/data/products.js (the static catalog the
// storefront has always used) into a SQL seed for the real `products` table
// (organic_food DB), so the new homepage sliders have a live table to query.
//
// Run once with: node backend/database/migrations/generate_pharmacy_products_seed.mjs
// Output: backend/database/migrations/seed_pharmacy_products.sql
//
// Field mapping notes:
// - DB has no `brand` column, so brand is stored in the unused `subtitle` column.
// - DB `price` = current selling price, `original_price` = pre-discount price
//   (opposite direction from the static file's price/salePrice pair).
// - DB `images`/`badges`/`tags`/`benefits`/`how_to_use` are JSON columns.
// - DB `stock` is a boolean ("in stock"), not a quantity.
// - Lab-chemical-specific fields (quantities, packaging, labSpecifications,
//   documents) have no matching columns and are intentionally dropped — the
//   DB copy only needs to support slider card display + category filtering;
//   the product detail page keeps reading the rich static record by slug.

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const productsPath = path.resolve(__dirname, '../../../src/data/products.js');
const outPath = path.resolve(__dirname, 'seed_pharmacy_products.sql');

const { products } = await import(pathToFileURL(productsPath).href);

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return "'" + String(value).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'";
}

function sqlJson(value) {
  if (value === null || value === undefined) return 'NULL';
  return sqlString(JSON.stringify(value));
}

function sqlNumber(value) {
  if (value === null || value === undefined || Number.isNaN(value)) return 'NULL';
  return String(value);
}

const rows = products.map((p) => {
  const sellingPrice = p.salePrice ?? p.price;
  const originalPrice = p.salePrice ? p.price : null;
  const discount = p.salePrice ? Math.round(((p.price - p.salePrice) / p.price) * 100) : null;

  const images = [p.image, ...(Array.isArray(p.gallery) ? p.gallery.filter((g) => g !== p.image) : [])];
  const howToUse = p.directions ? [{ step: '01', text: p.directions }] : null;

  return {
    name: p.name,
    slug: p.slug,
    subtitle: p.brand ?? null,
    category: p.category ?? null,
    size: p.weight ?? null,
    price: sellingPrice,
    original_price: originalPrice,
    discount,
    rating: p.rating ?? null,
    reviews: p.reviewCount ?? 0,
    stock: (p.stock ?? 0) > 0 ? 1 : 0,
    featured: Array.isArray(p.tags) && p.tags.includes('spotlight') ? 1 : 0,
    images,
    badges: p.badges ?? null,
    description: p.description ?? null,
    benefits: p.keyBenefits ?? null,
    ingredients: p.ingredients ?? null,
    how_to_use: howToUse,
    tags: p.tags ?? null,
    is_active: 1,
  };
});

const columns = [
  'name', 'slug', 'subtitle', 'category', 'size',
  'price', 'original_price', 'discount', 'rating', 'reviews',
  'stock', 'featured', 'images', 'badges', 'description',
  'benefits', 'ingredients', 'how_to_use', 'tags', 'is_active',
];

const valueLines = rows.map((r) => {
  const values = [
    sqlString(r.name),
    sqlString(r.slug),
    sqlString(r.subtitle),
    sqlString(r.category),
    sqlString(r.size),
    sqlNumber(r.price),
    sqlNumber(r.original_price),
    sqlNumber(r.discount),
    sqlNumber(r.rating),
    sqlNumber(r.reviews),
    sqlNumber(r.stock),
    sqlNumber(r.featured),
    sqlJson(r.images),
    sqlJson(r.badges),
    sqlString(r.description),
    sqlJson(r.benefits),
    sqlString(r.ingredients),
    sqlJson(r.how_to_use),
    sqlJson(r.tags),
    sqlNumber(r.is_active),
  ];
  return '  (' + values.join(', ') + ')';
});

const sql = `-- Generated by generate_pharmacy_products_seed.mjs — do not hand-edit.
-- Imports the ${rows.length} products from src/data/products.js into the real
-- \`products\` table so homepage sliders (and any future live-data feature)
-- have real rows to query. Slugs are preserved verbatim so /product/{slug}
-- still resolves against the static file the rest of the storefront uses.
--
-- Note: numeric ids are NOT forced to match the static file's ids, because
-- ids 1-10 in this table are already occupied by an unrelated seed (a
-- ghee/honey/herbal product set left over from a shared backend template).
-- Cart/wishlist line-item dedup keys on numeric product id, so a product
-- added from a slider (DB id) and the same product added from its detail
-- page (static id) could appear as two cart lines — a pre-existing
-- consequence of running two parallel catalogs, not something this seed
-- can fix without touching Cart/ProductDetail (out of scope here).

INSERT INTO \`products\`
  (\`${columns.join('`, `')}\`)
VALUES
${valueLines.join(',\n')};
`;

writeFileSync(outPath, sql, 'utf8');
console.log(`Wrote ${rows.length} product rows to ${outPath}`);
